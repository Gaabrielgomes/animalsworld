CREATE TABLE animals (
    id BIGINT NOT NULL AUTO_INCREMENT,
    name VARCHAR(150) NOT NULL,
    birth_date DATE,
    death_date DATE,
    mother_id BIGINT,
    father_id BIGINT,
    gender VARCHAR(10),
    race VARCHAR(100),
    specie VARCHAR(100) NOT NULL,
    animal_class VARCHAR(20),
    extinction_warning TINYINT(1),
    active TINYINT(1) NOT NULL DEFAULT 1,
    PRIMARY KEY (id),
    CONSTRAINT fk_animals_mother FOREIGN KEY (mother_id) REFERENCES animals (id),
    CONSTRAINT fk_animals_father FOREIGN KEY (father_id) REFERENCES animals (id)
);

CREATE TABLE tours (
    id BIGINT NOT NULL AUTO_INCREMENT,
    guide_id BIGINT NOT NULL,
    tour_schedule DATETIME NOT NULL,
    active TINYINT(1) NOT NULL DEFAULT 1,
    PRIMARY KEY (id),
    CONSTRAINT fk_tours_guide FOREIGN KEY (guide_id) REFERENCES guides (id)
);

CREATE TABLE tour_visitors (
    tour_id BIGINT NOT NULL,
    visitor_id BIGINT NOT NULL,
    PRIMARY KEY (tour_id, visitor_id),
    CONSTRAINT fk_tour_visitors_tour FOREIGN KEY (tour_id) REFERENCES tours (id),
    CONSTRAINT fk_tour_visitors_visitor FOREIGN KEY (visitor_id) REFERENCES visitors (id)
);
