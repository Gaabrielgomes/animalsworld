CREATE TABLE employees (
    id BIGINT NOT NULL AUTO_INCREMENT,
    name VARCHAR(150) NOT NULL,
    email VARCHAR(150) NOT NULL,
    phone VARCHAR(20),
    ssn VARCHAR(11) NOT NULL,
    birth_date DATE,
    gender VARCHAR(10),
    login VARCHAR(50) NOT NULL,
    password VARCHAR(255) NOT NULL,
    specialization VARCHAR(20),
    contract_type VARCHAR(20),
    working_shift VARCHAR(20),
    working_situation VARCHAR(30),
    resident_name VARCHAR(150),
    street_number INT,
    predirectional VARCHAR(10),
    street_name VARCHAR(150),
    street_suffix VARCHAR(20),
    postdirectional VARCHAR(10),
    sec_address_identifier VARCHAR(50),
    city VARCHAR(100),
    state VARCHAR(50),
    zip_code VARCHAR(10),
    delivery_point VARCHAR(10),
    country VARCHAR(50),
    complement VARCHAR(150),
    active TINYINT(1) NOT NULL DEFAULT 1,
    PRIMARY KEY (id),
    UNIQUE KEY uk_employees_ssn (ssn),
    UNIQUE KEY uk_employees_login (login)
);

